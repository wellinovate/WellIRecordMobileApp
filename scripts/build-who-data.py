"""Builds src/data/whoGrowth.ts from the WHO Child Growth Standards LMS tables.

The tables come from the `pygrowup` package (UNICEF, BSD licence), which ships the WHO
0-5 year tables unchanged: `pip download pygrowup --no-deps && tar xzf pygrowup-*.tar.gz`,
then `python3 scripts/build-who-data.py pygrowup-0.8.2/pygrowup/tables`.

Weight-for-age, head-circumference-for-age and length/height-for-age, 0 to 60 months, boys and girls.
Length-for-age (lying down) runs 0 to 24 months and height-for-age (standing) 24 to 60 months;
the tables hold two rows for month 24, in that order.
"""
import json, sys, os

src = sys.argv[1]
out = os.path.join(os.path.dirname(__file__), '..', 'src', 'data', 'whoGrowth.ts')

def load(name):
    return json.load(open(os.path.join(src, name + '_zscores.json')))

def lms(rows):
    return [[float(r['L']), float(r['M']), float(r['S'])] for r in rows]

def sd_tables(rows):
    # the published rounded -3,-2,0,+2,+3 SD values, kept only so tests can cross-check the formula
    return [[float(r[k]) for k in ('SD3neg', 'SD2neg', 'SD0', 'SD2', 'SD3')] for r in rows]

data = {}
for sex in ('boys', 'girls'):
    wfa = load(f'wfa_{sex}_0_5')
    hc = load(f'hcfa_{sex}_0_5')
    lh = load(f'lhfa_{sex}_0_5')
    months = [int(r['Month']) for r in lh]
    first24 = months.index(24)
    second24 = months.index(24, first24 + 1)
    length_rows = lh[: first24 + 1]
    height_rows = lh[second24:]
    assert [int(r['Month']) for r in wfa] == list(range(61))
    assert [int(r['Month']) for r in hc] == list(range(61))
    assert [int(r['Month']) for r in length_rows] == list(range(25))
    assert [int(r['Month']) for r in height_rows] == list(range(24, 61))
    data[sex] = {
        'weight': {'start': 0, 'lms': lms(wfa), 'sd': sd_tables(wfa)},
        'head': {'start': 0, 'lms': lms(hc), 'sd': sd_tables(hc)},
        'length': {'start': 0, 'lms': lms(length_rows), 'sd': sd_tables(length_rows)},
        'height': {'start': 24, 'lms': lms(height_rows), 'sd': sd_tables(height_rows)},
    }

with open(out, 'w') as f:
    f.write('''// WHO Child Growth Standards, 0 to 60 months. LMS values per completed month.
//
// Source: WHO Child Growth Standards (2006) weight-for-age, length/height-for-age and
// head-circumference-for-age tables, as shipped unchanged in the pygrowup package
// (UNICEF, BSD licence). Generated by scripts/build-who-data.py. Do not edit by hand.
//
// REVIEW STATUS: the WHO tables are a published standard. How the app words and uses them
// is not yet signed off, so growth charts show as pending clinical review in the app.
// `sd` holds the rounded -3, -2, 0, +2, +3 SD values from the same tables, used only by tests.

export type GrowthMetric = 'weight' | 'length' | 'height' | 'head';
export type GrowthSex = 'boys' | 'girls';

export interface GrowthTable {
  /** Age in months of the first row. */
  start: number;
  /** [L, M, S] per month. */
  lms: [number, number, number][];
  /** [-3SD, -2SD, median, +2SD, +3SD], rounded to 0.1. */
  sd: [number, number, number, number, number][];
}

export const WHO_GROWTH_REVIEW = { reviewStatus: 'pending_clinical_review' as 'pending_clinical_review' | 'reviewed', reviewedBy: null as string | null, reviewedOn: null as string | null };

export const WHO_GROWTH: Record<GrowthSex, Record<GrowthMetric, GrowthTable>> = ''')
    f.write(json.dumps(data, separators=(',', ':')).replace('"weight"', 'weight').replace('"head"', 'head').replace('"length"', 'length').replace('"height"', 'height').replace('"start"', 'start').replace('"lms"', 'lms').replace('"sd"', 'sd').replace('"boys"', 'boys').replace('"girls"', 'girls'))
    f.write(' as unknown as Record<GrowthSex, Record<GrowthMetric, GrowthTable>>;\n')
print('wrote', out)
